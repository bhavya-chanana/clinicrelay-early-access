// Builds dist/ from public/ and writes dist/config.js from environment variables.
// Locally, values come from .env (if present); in GitHub Actions, from repo Variables.
// No dependencies. Usage: node scripts/build.mjs
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const envFile = join(root, ".env");

// Minimal .env loader: KEY=value lines; real environment variables win.
if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (!m || line.trim().startsWith("#")) continue;
    const value = m[2].replace(/^(['"])(.*)\1$/, "$2");
    if (process.env[m[1]] === undefined || process.env[m[1]] === "") process.env[m[1]] = value;
  }
}

const errors = [];
const str = (k, test, why) => {
  const v = (process.env[k] || "").trim();
  if (v && test && !test(v)) errors.push(`${k}: ${why}`);
  return v;
};
const num = (k, dflt) => {
  const raw = (process.env[k] || "").trim();
  if (!raw) return dflt;
  const n = Number(raw);
  if (!Number.isInteger(n) || n < 0) errors.push(`${k}: must be a whole number`);
  return n;
};
const https = (v) => /^https:\/\/[^\s"'<>]+$/.test(v);

const config = {
  PAYMENT_URL: str("PAYMENT_URL", https, "must be an https:// URL"),
  ONBOARDING_ENDPOINT: str("ONBOARDING_ENDPOINT", https, "must be an https:// URL"),
  WHATSAPP_NUMBER: str("WHATSAPP_NUMBER", (v) => /^\d{10,15}$/.test(v), "digits only, with country code, e.g. 919876543210"),
  CONTACT_EMAIL: str("CONTACT_EMAIL", (v) => /^[^\s@"'<>]+@[^\s@"'<>]+\.[^\s@"'<>]+$/.test(v), "not an email address"),
  DEPOSIT_INR: num("DEPOSIT_INR", 999),
  FOUNDING_PRICE_INR: num("FOUNDING_PRICE_INR", 1999),
  LIST_PRICE_INR: num("LIST_PRICE_INR", 2499),
  SETUP_FEE_INR: num("SETUP_FEE_INR", 5000),
  FOUNDING_LOCK_MONTHS: num("FOUNDING_LOCK_MONTHS", 6),
  FOUNDING_SPOTS: num("FOUNDING_SPOTS", 25),
};
if (errors.length) {
  console.error("Config errors:\n  " + errors.join("\n  "));
  process.exit(1);
}

const dist = join(root, "dist");
rmSync(dist, { recursive: true, force: true });
mkdirSync(dist);
cpSync(join(root, "public"), dist, { recursive: true });
writeFileSync(join(dist, "config.js"),
  "// Generated by scripts/build.mjs. Do not edit.\nwindow.CLINICRELAY_SITE = " +
  JSON.stringify(config, null, 2) + ";\n");
writeFileSync(join(dist, ".nojekyll"), "");

// Report what is configured without echoing values.
const missing = ["PAYMENT_URL", "ONBOARDING_ENDPOINT", "WHATSAPP_NUMBER"].filter((k) => !config[k]);
console.log("Built dist/." + (missing.length ? " Not set yet: " + missing.join(", ") : " All links set."));
